/**
 * Имя, которым говорящий называет САМОГО СЕБЯ, — или пусто.
 *
 * Только три оборота, и все три однозначны: «I am Dana», «I'm Dana», «My name
 * is Dana». Всё прочее упоминание имени говорит о другом человеке, и брать его
 * нельзя: в строке «This is Dana.» говорит кто угодно, только не Дана.
 */
export function ktoGovorit(replika: string): string | null {
  const m =
    /\bI(?:\s+am|'m)\s+([A-Z][a-z]+)/.exec(replika) ??
    /\bMy\s+name\s+is\s+([A-Z][a-z]+)/.exec(replika);
  return m ? m[1] : null;
}
