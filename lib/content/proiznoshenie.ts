/**
 * Как читать имена собственные.
 *
 * Наши источники транскрипции таких слов не знают и знать не могут: частотные
 * словники составляются по нарицательным словам, и `Aigerim` в них не будет
 * никогда. Поэтому каждая строка здесь — решение владельца как преподавателя,
 * принятое 16 августа 2026 после прослушивания пробы.
 *
 * Дальше эти записи уходят в разметку `<phoneme>` при озвучке. Без них машина
 * читает наши имена как попало: `Aigerim` становится «эйджерим», `Almaty` —
 * «алмэти».
 *
 * Отдельно про города. `Almaty` и `Astana` англичанин произнесёт по-своему
 * (`/ˈælmətiː/`, `/æsˈtɑːnə/`). Взято казахское чтение: курс для казахстанцев,
 * и ученик должен уметь назвать свой город так, как он называется.
 *
 * ВАЖНО. Правка любой строки здесь означает переозвучку всех записей, где это
 * слово встречается. Скрипт `npm run ozvuchka` делает это сам — он помнит, из
 * чего сделан каждый файл, — но переделать он может только то, что запущено.
 */
export const PROIZNOSHENIE: Record<string, string> = {
  Aigerim: "ˌaɪɡeˈriːm",
  Aigul: "aɪˈɡuːl",
  Alim: "ɑːˈliːm",
  Almaty: "ˌɑːlmɑːˈtiː",
  Astana: "ˌæstɑːˈnɑː",
  Dana: "dɑːˈnɑː",
  Kazakhstan: "ˌkæzəkˈstɑːn",
  Nurlan: "nʊrˈlɑːn",
};

/**
 * Свести все записи в одну строку — по ней скрипт озвучки понимает, что
 * произношение поменялось и записи пора переделать.
 */
export function otpechatokProiznosheniya(): string {
  return Object.entries(PROIZNOSHENIE)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([slovo, mfa]) => `${slovo}=${mfa}`)
    .join(";");
}
