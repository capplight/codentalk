import { test } from "node:test";
import assert from "node:assert/strict";
import { razobrat } from "./razbor-stroki.ts";

/*
 * РАЗБОР СТРОКИ ОБЪЯСНЕНИЯ. Испытания написаны 11 сентября 2026, когда функция
 * переехала сюда из `components/lesson/Ekran.tsx`.
 *
 * До того дня вид строки на экране проверялся только глазами и копиями
 * регулярного выражения в записках проверяющих. Именно так 26 строк модуля 15
 * стояли с английским ответом в русском столбце и немой кнопкой звука, пока
 * редактор не прогнал копию разбора сам.
 */

test("обычная пара: английская строка и перевод", () => {
  assert.deepEqual(razobrat("I am Alim. — Я Алим."), { en: "I am Alim.", ru: "Я Алим." });
});

test("тире внутри перевода остаётся в переводе", () => {
  assert.deepEqual(razobrat("This thing is a clock. — Эта вещь — часы."), {
    en: "This thing is a clock.",
    ru: "Эта вещь — часы.",
  });
});

test("диктовка по буквам: перевод начинается латиницей и всё равно перевод", () => {
  // Первая редакция правила о «вопрос — ответ» ломала ровно эти строки модуля 1:
  // пропускала всякое тире перед латинской буквой.
  assert.deepEqual(razobrat("K-I-M. Kim. — K-I-M. Ким."), {
    en: "K-I-M. Kim.",
    ru: "K-I-M. Ким.",
  });
  assert.deepEqual(razobrat("N-U-R-L-A-N. Thank you. — N-U-R-L-A-N. Спасибо."), {
    en: "N-U-R-L-A-N. Thank you.",
    ru: "N-U-R-L-A-N. Спасибо.",
  });
});

test("вопрос и ответ с переводом: пара целиком встаёт в английский столбец", () => {
  // Ровно эта строка модуля 15 показывала ответ в русском столбце.
  assert.deepEqual(razobrat("Do you work? — Yes, I do. — Ты работаешь? — Да."), {
    en: "Do you work? — Yes, I do.",
    ru: "Ты работаешь? — Да.",
  });
});

test("ответ со своим тире и переводом тоже разбирается", () => {
  assert.deepEqual(
    razobrat("Do your parents live here? — No, they don't. — Твои родители здесь живут? — Нет."),
    { en: "Do your parents live here? — No, they don't.", ru: "Твои родители здесь живут? — Нет." }
  );
});

test("вопрос и ответ без перевода — не пример, а строка правила", () => {
  // Такую строку показывает `sZvukom`, и кнопка у неё стоит по ключу звука.
  assert.equal(razobrat("Do you work? — Yes, I do."), null);
});

test("пара букв без перевода — не пример", () => {
  assert.equal(razobrat("G — J"), null);
});

test("тире перед транскрипцией не пропускается: за ним не латинская буква", () => {
  assert.deepEqual(razobrat("key — /kiː/ — ключ"), { en: "key", ru: "/kiː/ — ключ" });
});

test("русская строка правила без английского слева — не пример", () => {
  assert.equal(razobrat("Короткий ответ — это Yes или No и слово do."), null);
});

test("ловушка остаётся: английское слово слева от тире превращает правило в пару", () => {
  // Не беда кода, а беда слога: тире стоит вместо союза. Испытание держит
  // поведение нарочно, чтобы правка разбора не прятала ловушку молча.
  assert.deepEqual(razobrat("Слово do — служебное"), { en: "Слово do", ru: "служебное" });
});
