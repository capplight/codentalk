import type { Golos } from "./zvuk";

/**
 * Формат урока. Разбор и обоснование — docs/format-uroka.md.
 *
 * На этих типах будут написаны сотни уроков, поэтому здесь важнее строгость,
 * чем удобство: чем меньше свободы у автора, тем больше проверок можно сделать
 * скриптом и тем однообразнее выглядит курс для ученика.
 *
 * Виды заданий названы по QTI 3.0, чтобы банк вопросов можно было вывезти в
 * другую систему или ввезти чужой.
 */

// ---------------------------------------------------------------------------
// Имя блока
// ---------------------------------------------------------------------------

/**
 * Устойчивое имя блока внутри урока. Задаётся автором вручную и НЕ меняется
 * после выхода урока.
 *
 * Почему не порядковый номер и не отпечаток содержания: к блоку привязываются
 * пометки «непонятно» и заметки учеников. Номер съедет, стоит переставить два
 * абзаца; отпечаток съедет от исправленной опечатки. И в том, и в другом случае
 * пометки учеников молча переедут на чужое место — а это их работа, потерять её
 * нельзя. Имя, написанное руками, переживает и перестановку, и правку текста.
 */
export type BlockId = string;

interface BlockBase {
  /** Латиницей, через дефис, уникально внутри урока. Не менять после выхода. */
  id: BlockId;
  /**
   * Значок у экрана в пошаговом виде урока: код знака Twemoji, например
   * `1f697` — машина.
   *
   * ЗАЧЕМ ЗДЕСЬ, А НЕ В КОДЕ СТРАНИЦЫ. Картинка — часть содержания: её
   * выбирает тот, кто пишет урок, и меняет вместе с текстом. В первой
   * редакции соответствие «имя блока → знак» лежало в скрипте образца, и
   * стоило переименовать блок, как картинка молча пропадала.
   *
   * Файлы лежат у нас в `public/twemoji`, а не тянутся с чужого адреса: то же
   * правило, по которому шрифты забираются во время сборки. Забирает их
   * `npm run znachki`.
   *
   * Twemoji — CC-BY 4.0, упоминание стоит в подвале сайта.
   */
  znak?: string;
  /**
   * СКОЛЬКО РАЗ РИСОВАТЬ ЗНАЧОК. Пусто — один.
   *
   * Решение владельца от 6 сентября 2026: «Чини». Сказано о задании, где
   * условие говорит «на столе четыре чашки», а страница ставила один значок, —
   * ученик читал одно, а видел другое. На счёте держится целый модуль «Один и
   * много», и картинка, врущая о числе, там хуже отсутствующей.
   *
   * Больше десяти не рисуется: на телефоне ряд из двенадцати чашек не
   * сосчитать. Запрещает `check:content`.
   */
  znakov?: number;
}

