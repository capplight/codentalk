/** Объяснение. Основа урока: течёт по странице серифным шрифтом. */
export interface ExplainBlock extends BlockBase {
  kind: "explain";
  /** Абзацы. Разделение на абзацы — обязанность автора, а не переносы в строке. */
  text: string[];
  /**
   * ЧТО В ОБЪЯСНЕНИИ МОЖНО ПОСЛУШАТЬ. Ключ — кусок строки ровно как напечатан
   * (`/biː/`, `B`), значение — что произнести (`B`).
   *
   * ЗАЧЕМ. Решение владельца от 4 сентября 2026: «ученик не знает как читать
   * транскрипцию, поэтому звучание букв тоже надо рядом добавить… рядом с самой
   * транскрипцией или же буквой должна быть кнопка звука, чтобы прослушать».
   * Раньше звук стоял только в таблице, которая шла ОТДЕЛЬНЫМ экраном: ученик
   * читал `/dʒeɪ/` и не мог услышать это здесь же.
   *
   * Устроено так же, как у примера и таблицы, и той же записью
   * (`zvuchashchee`): значение задаёт имя файла, поэтому одно и то же название
   * буквы в объяснении и в таблице — одна запись, а не две.
   */
  zvuk?: Record<string, string>;
  /**
   * Куски, которые звучат сами собой: что напечатано, то и произносится.
   *
   * Так же, как у примера и таблицы. Появилось у объяснения 5 сентября 2026:
   * в уроке о порядке букв кнопки нужны у самих букв `A` и `Z`, а писать это
   * парой «A: A» значит записывать одно и то же дважды — `check:content` на
   * такую пару и указывает.
   */
  zvuchat?: string[];
  /**
   * ГОЛОСА, ЕСЛИ СТРОКА — РАЗГОВОР. Решение владельца от 6 сентября 2026: «нам
   * нужно два голоса, переделывай. а еще женские имена с женским голосом,
   * мужские с мужским».
   *
   * Строка вида `How many apples are there? — Three.` внутри объяснения, врезки
   * или таблицы звучит на два голоса, как запись и как пример-разговор. Признак
   * разговора считает `razgovorVStroke()` — и он НЕ тот же, что у записей: тире
   * здесь чаще значит пару (`work — worked`), а не смену говорящего.
   *
   * Полей два, и второе сильнее: `pervyyGolos` сдвигает чередование,
   * `golosa` называет голос каждой реплики поимённо. У строки, разговором не
   * являющейся, оба поля не значат ничего.
   */
  pervyyGolos?: Golos;
  golosa?: Golos[];
}

/** Разобранный пример. Показывается ДО самостоятельной попытки. */
export interface ExampleBlock extends BlockBase {
  kind: "example";
  caption?: string;
  /** Либо код, либо текст на изучаемом языке — но что-то одно должно быть. */
  code?: string;
  text?: string;
  /** Разбор: почему пример устроен именно так. Без него это не пример, а картинка. */
  explain: string;
  /**
   * Звучащие строки примера: ключ — строка как она записана в `text`,
   * значение — что произнести.
   *
   * ЗАЧЕМ. Решение владельца от 19 августа: звук стоит там, где ученик читает.
   * Отдельная запись под примером новичку не говорит ничего — он видит набор
   * слов и не знает, к чему они. Услышать надо ровно то, на что смотришь.
   *
   * Дробится по единицам: пара «G — J» одна запись, «B — V» другая. Одной
   * записью на весь пример обходятся только разговоры — для них `razgovor`.
   *
   * Нужно только там, где произносится НЕ ТО, что напечатано. Обычный случай —
   * `zvuchat` ниже.
   */
  zvuk?: Record<string, string>;
  /**
   * Строки, которые звучат сами собой: что напечатано, то и произносится.
   *
   * Это обычный случай, и записывать его парой «строка: та же строка» значило
   * бы писать каждую фразу дважды. `zvuk` остаётся для расхождений.
   */
  zvuchat?: string[];
  /**
   * Разговор целиком, одной кнопкой и НА ДВА ГОЛОСА.
   *
   * Реплики делятся по строкам примера. Разговор должен звучать разговором, а
   * не одним длинным предложением, — поэтому голоса чередуются, а не читают
   * всё подряд одним.
   */
  razgovor?: boolean;
  /**
   * КТО ГОВОРИТ ПЕРВЫМ — женский голос или мужской.
   *
   * По умолчанию первым читает женский: так собраны все прежние разговоры
   * курса, и менять их молча нельзя. Ставится там, где пол говорящего задан
   * содержанием.
   *
   * ЗАЧЕМ. Владелец 5 сентября 2026 послушал сцену первого урока и сказал:
   * «Дана это женское имя в Казахстане». Голоса чередуются, и гостья, чья
   * реплика вторая, читалась мужским голосом.
   *
   * ОСТОРОЖНО, И ЭТО ИЗМЕНИЛОСЬ 6 сентября 2026. Прежде порядок голосов в имя
   * файла не входил, и два одинаковых разговора с разным порядком давали одну
   * запись; скрипт озвучки переписывал её то так, то этак. Теперь раскладка
   * голосов входит в ключ (`raskladkaGolosov` в `lib/content/zvuk.ts`), и такие
   * записи — разные файлы. Обычный расклад (женский первым) в ключ не входит,
   * поэтому имена всех прежних записей остались прежними.
   */
  pervyyGolos?: Golos;
  /**
   * ГОЛОС КАЖДОЙ РЕПЛИКИ ПО ПОРЯДКУ — решение владельца от 6 сентября 2026.
   *
   * Он сказал: «нам нужно два голоса, переделывай. а еще женские имена с
   * женским голосом, мужские с мужским», и отдельным ответом: «голос у каждой
   * реплики отдельным полем — делай».
   *
   * ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ `pervyyGolos`. Тот сдвигает ЧЕРЕДОВАНИЕ: женский —
   * мужской — женский либо наоборот. Пока в сцене двое и говорят они по
   * очереди, этого хватает. Не хватает там, где один человек говорит две
   * реплики подряд или где говорящих трое: чередование даёт им разные голоса,
   * хотя человек тот же.
   *
   * Длина обязана совпасть с числом реплик — это проверяет `check:content`.
   * Короче или длиннее значит, что реплики переписали, а голоса остались от
   * прежней сцены.
   */
  golosa?: Golos[];
  /**
   * Русский перевод строк примера: ключ — строка как она записана в `text`,
   * значение — перевод.
   *
   * ЗАЧЕМ. Просьба владельца от 30 августа 2026: объяснения читаются
   * механически, потому что английская строка стоит без перевода и ученик
   * должен догадываться. Счёт по курсу на тот день: 1390 строк примеров с
   * английским, перевод рядом — у нуля.
   *
   * Устроено как `zvuk` нарочно: ключом служит та же строка, значит `text` и
   * `zvuchat` не меняются, имена звуковых файлов остаются прежними и
   * переозвучка не нужна.
   *
   * Переводятся не все строки: русской подписи, дате цифрой и заголовку
   * объявления перевод не нужен. Строка, показывающая, как говорить нельзя,
   * перевода не получает тоже — иначе неверная фраза запомнится наравне с
   * верной.
   */
  perevod?: Record<string, string>;
}

/** Таблица: формы, спряжения, сопоставления — то, что списком не читается. */
