/**
 * Строка объяснения — это пример, если в ней есть и английское, и русское, и
 * они разделены тире.
 *
 * На этом держится правило «у случая два примера с переводом»: автор пишет
 * `I am Alim. — Я Алим.`, а показывается это карточкой, где английское сверху
 * и крупно, а перевод под ним и тише. Разбирать строку разметкой автору не
 * приходится.
 *
 * ---------------------------------------------------------------------------
 * ТИРЕ ПЕРЕД ЧИСТО АНГЛИЙСКИМ КУСКОМ ПЕРЕВОД НЕ НАЧИНАЕТ
 * ---------------------------------------------------------------------------
 *
 * Правило приписано 11 сентября 2026, и нашёл беду редактор модуля 15, а не
 * проверка.
 *
 * Прежде строка резалась по ПЕРВОМУ тире. Модуль 15 учит короткому ответу и
 * пишет пару «вопрос — ответ» вместе с переводом:
 *
 *   Do you work? — Yes, I do. — Ты работаешь? — Да.
 *
 * Первое тире здесь делит английское с английским, и на экране выходило вот
 * что: в английском столбце стоял один вопрос, а ответ `Yes, I do.` уезжал в
 * русский столбец вместе с переводом — без английской разметки и без кнопки
 * звука. Звук при этом молчал совсем: ключ звука записан всей парой
 * «вопрос — ответ», а кнопка ищется по английскому столбцу, где стоял один
 * вопрос. Проверка содержания была довольна, потому что ключ как кусок в
 * строке есть.
 *
 * Теперь тире пропускается, если кусок за ним до следующего тире ЧИСТО
 * АНГЛИЙСКИЙ: начинается латинской буквой и не несёт ни одной русской. Пара
 * «вопрос — ответ» встаёт в английский столбец целиком, совпадает с ключом
 * звука и звучит на два голоса, как требует решение владельца от 6 сентября
 * 2026 о строке-разговоре внутри объяснения.
 *
 * ПЕРВАЯ РЕДАКТУРА ЭТОГО ПРАВИЛА БЫЛА ШИРЕ И СЛОМАЛА МОДУЛЬ 1 — стоит помнить,
 * чем. Она пропускала всякое тире, за которым сразу идёт латинская буква. А
 * перевод диктовки по буквам латиницей и начинается — так велит оговорка к
 * переводу («диктовка по буквам не переводится русскими буквами»):
 *
 *   K-I-M. Kim. — K-I-M. Ким.
 *
 * Восемь таких строк модуля 1 перестали бы быть парами. Новая проверка немых
 * кнопок этого не видела: у строки правила кнопка остаётся. Поймал прогон
 * старого разбора против нового по всем объяснениям курса. Отсюда признак
 * «нет ни одной русской буквы в куске», а не «первая буква латинская».
 *
 * Тире внутри перевода (`This thing is a clock. — Эта вещь — часы.`) и тире
 * перед транскрипцией (`/kiː/`) правило не трогает: за первым кусок русский, за
 * вторым начинается не с латинской буквы.
 *
 * ЛОВУШКА, КОТОРАЯ ОСТАЛАСЬ И ОСТАНЕТСЯ: русская строка правила с тире, где
 * слева стоит английское слово, по-прежнему встаёт парой. Правило «Слово do —
 * служебное» покажется английским столбцом «Слово do». Чинится это слогом, а не
 * кодом: тире там стоит вместо союза. Записано в CLAUDE.md, раздел «Тире в
 * строке правила».
 *
 * ПОЧЕМУ ФУНКЦИЯ ЖИВЁТ ЗДЕСЬ, А НЕ В `components/lesson/Ekran.tsx`. Правило
 * проекта: всё, что решает, что увидит ученик, лежит там, где его можно
 * испытать. Из компонента страницы функцию позвать тестом было нельзя: он тянет
 * React и стили. Испытания — `razbor-stroki.test.ts`.
 */
export function razobrat(stroka: string): { en: string; ru: string } | null {
  const mesta: { nachalo: number; konec: number }[] = [];
  const razdelitel = /\s+—\s+/g;
  let m: RegExpExecArray | null;
  while ((m = razdelitel.exec(stroka)) !== null) {
    mesta.push({ nachalo: m.index, konec: m.index + m[0].length });
  }

  for (let i = 0; i < mesta.length; i++) {
    const levo = stroka.slice(0, mesta[i].nachalo);
    const pravo = stroka.slice(mesta[i].konec);
    const kusok = stroka.slice(
      mesta[i].konec,
      i + 1 < mesta.length ? mesta[i + 1].nachalo : stroka.length
    );
    // «Вопрос — ответ»: кусок за тире чисто английский, перевод дальше.
    if (/^[A-Za-z]/.test(kusok) && !/[А-Яа-яЁё]/.test(kusok)) continue;
    if (!/[A-Za-z]{2,}/.test(levo)) return null;
    if (!/[А-Яа-яЁё]{2,}/.test(pravo)) return null;
    return { en: levo.trim(), ru: pravo.trim() };
  }
  return null;
}
