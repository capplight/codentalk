/** Подпись над экраном материала — по виду блока. */
export function podpisMateriala(kind: string): string {
  switch (kind) {
    case "example":
      return "как это звучит";
    case "table":
      return "таблица";
    case "note":
      return "важно";
    case "vocab":
      return "слова урока";
    case "audio":
      return "послушай";
    case "text":
      return "текст для чтения";
    case "image":
      return "картинка";
    default:
      return "смотрим";
  }
}

/**
 * Подпись над объяснением: которое оно по счёту.
 *
 * «Правило», а не «разбор»: на экране стоит имя случая и правило одной строкой,
 * а слово «разбор» ученик отнесёт к разбору задания, который у нас тоже есть.
 */
export function podpisRazbora(kakoy: number, vsego: number): string {
  return `правило ${kakoy} из ${vsego}`;
}

/** Подпись над заданием. */
export function podpisZadaniya(kakoe: number, vsego: number): string {
  return `задание ${kakoe} из ${vsego}`;
}

