/**
 * Адрес картинки значка.
 *
 * ИСТОЧНИКОВ ДВА, И ЭТО РЕШЕНИЕ ВЛАДЕЛЬЦА, а не удобство. 3 сентября 2026 он
 * сказал «сделанные тобой картинки плохие», и своё рисование прекратилось;
 * основой стал Twemoji (CC-BY 4.0, 3600 значков в одном стиле), а вторым
 * источником — Openclipart (CC0), «всё, чего нет у Twemoji»
 * (`docs/beginner-2/kartinki-otkuda.md`).
 *
 * Второй источник понадобился 6 сентября 2026, когда владелец потребовал
 * картинку почти у каждой карточки: «Желательно не оставляй без картинок ни
 * одну карточку». Сборщик раздал 52 значка и честно назвал слова, которым
 * значка в Twemoji НЕТ. Первым в том списке стоял `table` — та самая карточка,
 * с которой владелец и начал замечание.
 *
 * КАК РАЗЛИЧАЮТСЯ. Код Twemoji — это шестнадцатеричные числа через дефис
 * (`1f697`, `1f9d1-200d-1f3eb`), и другого вида у него не бывает. Всё
 * остальное — имя файла в `public/kartinki`. Правило одно и живёт здесь, а не
 * в шести местах разметки: разойдись они, и ученик получил бы сломанную
 * картинку при чистом отчёте — на этом проект уже обжигался с компасом
 * вступления.
 */
export function adresZnachka(kod: string): string {
  return /^[0-9a-f]+(-[0-9a-f]+)*$/.test(kod)
    ? `/twemoji/${kod}.svg`
    : `/kartinki/${kod}.svg`;
}
