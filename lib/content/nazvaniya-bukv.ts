/**
 * КАК ЗВУЧИТ ОТДЕЛЬНАЯ БУКВА — таблица для синтеза речи.
 *
 * ЗАЧЕМ. Владелец 5 сентября 2026 прошёл первый урок и сказал: «есть проблемы
 * со звуком… A хрипит, V тоже хрипит, C-A-T тут A хрипит сильно, звучит как K.
 * Эти звуки тяжело разобрать».
 *
 * Причина была в том, КАК мы просили синтез читать букву. Он получал
 * `<say-as interpret-as="characters">A</say-as>` и замедление на четверть:
 * одиночный знак без гласного окружения синтез тянет как обрывок, и на
 * замедлении обрывок хрипит. У букв с коротким названием (A, V) это слышно
 * сильнее всего.
 *
 * Здесь лежит британское чтение каждой буквы, и озвучка отдаёт синтезу
 * `<phoneme>` — ту же разметку, которой давно читаются имена собственные
 * (`proiznoshenie.ts`). Синтез получает не знак, а звук, и тянуть ему нечего.
 *
 * ОТКУДА ЗНАЧЕНИЯ. Из таблицы алфавита самого курса: она прошла и методиста, и
 * владельца, и переписывать выверенное значило бы заново нажить его ошибки.
 * Британская норма: `Z` — `zed`, а не `zee`; `W` — `/ˈdʌbljuː/`; краткий
 * гласный пишем через `e`, а не `ɛ`; согласный `r` — обычной буквой.
 *
 * ВАЖНО. Правка любой строки здесь означает переозвучку всех записей, где эта
 * буква звучит отдельно. Скрипт делает это сам: он помнит не текст, а разметку,
 * из которой сделан файл, и переделывает разошедшиеся.
 */
export const NAZVANIYA_BUKV: Record<string, string> = {
  A: "eɪ",
  B: "biː",
  C: "siː",
  D: "diː",
  E: "iː",
  F: "ef",
  G: "dʒiː",
  H: "eɪtʃ",
  I: "aɪ",
  J: "dʒeɪ",
  K: "keɪ",
  L: "el",
  M: "em",
  N: "en",
  O: "əʊ",
  P: "piː",
  Q: "kjuː",
  R: "ɑː",
  S: "es",
  T: "tiː",
  U: "juː",
  V: "viː",
  W: "ˈdʌbljuː",
  X: "eks",
  Y: "waɪ",
  Z: "zed",
};

/** Чтение буквы, если она у нас записана. Регистр не важен. */
export function chtenieBukvy(bukva: string): string | undefined {
  return NAZVANIYA_BUKV[bukva.trim().toUpperCase()];
}
