/**
 * Сколько верных ответов нужно для зачёта.
 *
 * Порог хранится долей (0.8) и в базе лежит баллами (80). Ученику ни то ни
 * другое не помогает: «нужно 80 баллов» он пересчитывает в уме, а ошибается в
 * пересчёте чаще, чем в самой работе. Поэтому наружу выходит счёт: «нужно 8
 * из 10».
 *
 * Округление вверх — в пользу строгости: при десяти вопросах и пороге 75%
 * нужно восемь верных, а не семь с половиной.
 */
export function nuzhnoVerno(passScore: number, voprosov: number): number {
  if (voprosov <= 0) return 0;
  return Math.min(voprosov, Math.ceil((passScore / 100) * voprosov));
}
