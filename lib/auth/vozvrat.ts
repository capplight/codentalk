/**
 * Куда вернуть человека после входа.
 *
 * Урок, закрытый до входа, передаёт свой адрес в `?dalshe=`. После входа туда и
 * возвращаем — иначе человек, нажавший на ссылку урока, попадает на главную и
 * ищет этот урок заново.
 *
 * ЗДЕСЬ ЖЕ ЗАЩИТА, И РАДИ НЕЁ ОТДЕЛЬНЫЙ ФАЙЛ. Адрес приходит из строки запроса,
 * то есть его пишет кто угодно. Без проверки ссылка вида
 * `/login?dalshe=https://чужой-сайт` увела бы человека на чужую страницу сразу
 * после ввода пароля — а он в этот миг доверяет всему, что видит. Поэтому
 * принимается только путь внутри сайта: начинается с одной косой черты и не
 * содержит второй следом.
 */

export const PO_UMOLCHANIYU = "/";

export function kudaVernutsya(adres: string | undefined | null): string {
  if (!adres) return PO_UMOLCHANIYU;
  // `//чужой-сайт` браузер считает полным адресом с той же схемой, поэтому
  // одной проверки на первую косую черту мало.
  if (!adres.startsWith("/") || adres.startsWith("//")) return PO_UMOLCHANIYU;
  // Обратная косая черта: часть браузеров равняет её с обычной, и `/\чужой`
  // уводит наружу так же.
  if (adres.startsWith("/\\")) return PO_UMOLCHANIYU;
  return adres;
}
