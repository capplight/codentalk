import { ApiError } from "./respond";

/**
 * Проверка имени записи из адреса.
 *
 * ЗАЧЕМ. Номера попыток и работ — это UUID, и они уходят прямо в запрос к базе.
 * База столбец такого вида разбирает сама и на мусор отвечает своей ошибкой:
 * обработчик ловит её и отдаёт «что-то пошло не так» с кодом 500.
 *
 * Это неверно дважды. Человеку показывают поломку там, где просто нет такой
 * записи. А в журнал сервера сыпятся ошибки базы, среди которых потом не видно
 * настоящих: любой, кто дёргает адреса наугад, заваливает журнал.
 *
 * Проверка формы до обращения к базе снимает и то и другое.
 */
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-9a-f][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

export function trebuetsyaUuid(znachenie: string, chegoNet: string): string {
  if (!UUID.test(znachenie)) {
    throw new ApiError("not_found", chegoNet);
  }
  return znachenie;
}
