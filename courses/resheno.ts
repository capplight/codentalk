/**
 * Разобранные случаи: то, о чём `npm run kontrol` больше не спрашивает.
 *
 * Зачем это нужно. Скрипт, который каждый раз спрашивает об одном и том же,
 * перестают читать — а вместе с новым вопросом теряется и старый. Поэтому у
 * каждой проверки должен быть способ замолчать навсегда: случай разобран,
 * решение принято, повторять его незачем.
 *
 * ПРАВИЛО, КОТОРОЕ ДЕРЖИТ ЭТОТ СПИСОК ЧЕСТНЫМ: запись без внятной причины —
 * сама по себе ошибка, и скрипт на ней останавливается. Иначе список за месяц
 * превратится в свалку, куда сбрасывают всё неудобное, и проверка умрёт тихо:
 * формально работает, а не находит ничего.
 *
 * Причина пишется так, чтобы через полгода её понял человек, который при
 * решении не присутствовал. «Так надо» и «проверено» причинами не считаются.
 */

export interface Resheno {
  /**
   * Что именно замолчать. Сравнивается по вхождению в текст замечания, поэтому
   * пиши узко: слово, цитату или её начало — но не «модуль 15».
   */
  chto: string;
  /** Почему это не ошибка. Не короче 30 знаков — иначе скрипт остановится. */
  pochemu: string;
  /** Кто решил: владелец, методист, редактор. */
  kto: "владелец" | "методист" | "редактор";
}

