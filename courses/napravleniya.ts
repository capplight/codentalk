export function findNapravlenie(slug: string): Napravlenie | undefined {
  return napravleniya.find((n) => n.slug === slug);
}

/** Имена курсов, которые входят в направления: каталог не показывает их поодиночке. */
export function kursyVNapravleniyah(): Set<string> {
  const out = new Set<string>();
  for (const n of napravleniya) {
    for (const s of n.stupeni) if (s.course) out.add(s.course);
  }
  return out;
}
