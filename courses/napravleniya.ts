/**
 * Направления и ступени внутри них.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Курс знает про себя всё, кроме одного: какое место он
 * занимает в лестнице. «Английский с нуля» не может назвать себя первой
 * ступенью — он не знает, что будет второй. Порядок ступеней живёт здесь.
 *
 * Решения владельца от 16 августа, на которых держится этот файл:
 *
 * 1. Курс называется по той ступени, К КОТОРОЙ ПРИВОДИТ. Beginner доводит до
 *    A1, Elementary — до A2, Pre-Intermediate — до B1. Это общепринятая связка,
 *    и менять её нельзя, иначе ученик, знающий свой уровень, выберет не то.
 * 2. Названия ступеней НЕ ПЕРЕВОДЯТСЯ ВОВСЕ: так их зовут во всём мире.
 *    Русского перевода рядом тоже не ставим — владелец сказал об этом дважды,
 *    и второй раз потому, что я всё-таки поставил.
 * 3. Замков нет. Ступень без курса помечена «готовится» — не потому, что она
 *    закрыта, а потому, что её ещё не написали.
 *
 * Веб-разработки здесь пока нет намеренно: там не ступени одной лестницы, а
 * разные темы, и порядок между ними другой. Решать это отдельно, когда
 * появится второй курс.
 */

export interface Stupen {
  /**
   * Имя курса, если он написан. Пусто — ступень готовится, карточка без
   * ссылки. Обещание, за которым ничего нет, хуже честного «готовится».
   */
  course?: string;
  /** Название ступени: Beginner, Elementary. Не переводится и не поясняется. */
  name: string;
  /** Ступень Совета Европы, к которой курс приводит: «до A1». */
  cefr: string;
  /** Одна-две строки: что человек сможет после этой ступени. */
  about: string;
}

export interface Napravlenie {
  slug: string;
  /** Название для карточки в каталоге: «Английский», а не «Английский язык». */
  title: string;
  tagline: string;
  /** Имя рисунка из components/CourseArt.tsx */
  art: string;
  stupeni: Stupen[];
}

